"""Generate src/app/board/audio/pwm_audio_interp_coeffs.h (48 kHz -> 192 kHz).

`--phases 8` writes pwm_audio_interp8_coeffs.h instead (48 -> 384 kHz, same
24-tap span): the 3-level backend takes the +V pulse from phase 2k and the
-V pulse from phase 2k+1, so each pulse is sampled at its own centre.

Kaiser-windowed sinc, L = 4 phases x 24 taps, cutoff 24 kHz, beta 6:
passband 0..20 kHz within +/-0.01 dB, images >= 28 kHz below -61 dB
(the 48k-f image of a 20 kHz tone is the nearest one). Every phase is
normalised to sum 1 so a constant duty stays constant.

Layout: c[j][k] multiplies window[j] for phase k (tap-major, so one pass
over the window feeds all phases); window[TAPS-1] = newest 48 kHz sample;
phase k is carrier period k of the frame. Group delay = 11.5 input samples.
"""
import pathlib
import sys
import numpy as np

L = 8 if sys.argv[1:] == ['--phases', '8'] else 4
TAPS, BETA, FC, FS = 24, 6.0, 24000.0, 48000.0
SUFFIX = '8' if L == 8 else ''


def phases():
    n = np.arange(L * TAPS) - (L * TAPS - 1) / 2
    h = np.sinc(2 * FC / (FS * L) * n) * np.kaiser(L * TAPS, BETA)
    c = np.empty((L, TAPS))
    for k in range(L):
        c[k] = [h[(TAPS - 1 - j) * L + k] for j in range(TAPS)]
        c[k] /= c[k].sum()
    return c.astype(np.float32).astype(np.float64)   # what the MCU really uses


def response(c, f):
    """Gain of the polyphase interpolator (ZOH not included) at f Hz."""
    h = np.empty(L * TAPS)
    for k in range(L):
        for j in range(TAPS):
            h[(TAPS - 1 - j) * L + k] = c[k][j]
    return np.abs(np.exp(-2j * np.pi * np.outer(f, np.arange(L * TAPS)) / (FS * L)) @ h) / L


def main():
    c = phases()
    f = np.linspace(0, FS * L / 2, 9601)
    g = 20 * np.log10(response(c, f) + 1e-30)
    pb, sb = g[f <= 20000], g[f >= 28000]
    root = pathlib.Path(__file__).resolve().parents[2]
    out = root / f'src/app/board/audio/pwm_audio_interp{SUFFIX}_coeffs.h'
    rows = ',\n'.join('    { ' + ', '.join(f'{v:.9e}f' for v in c[:, j]) + ' }' for j in range(TAPS))
    out.write_text(f'''/*
 * Generated by buildtools/pwm_sim/gen_pwm_interp_coeffs.py -- do not edit.
 * 48 kHz -> {FS * L / 1000:g} kHz polyphase interpolator for the AK PWM board backend.
 * Kaiser beta {BETA:g}, cutoff {FC:g} Hz, {L} phases x {TAPS} taps, each phase sums to 1.
 * Passband 0..20 kHz {pb.min():+.3f}..{pb.max():+.3f} dB, >= 28 kHz <= {sb.max():.1f} dB.
 * c[j][k] multiplies window[j] for phase k; window[{TAPS - 1}] is the newest sample.
 */
#ifndef PWM_AUDIO_INTERP{SUFFIX}_COEFFS_H
#define PWM_AUDIO_INTERP{SUFFIX}_COEFFS_H

#define PWM_AUDIO_INTERP{SUFFIX}_PHASES {L}u
#define PWM_AUDIO_INTERP{SUFFIX}_TAPS   {TAPS}u

static const float pwm_audio_interp{SUFFIX}_coeffs[PWM_AUDIO_INTERP{SUFFIX}_TAPS][PWM_AUDIO_INTERP{SUFFIX}_PHASES] = {{
{rows}
}};

#endif /* PWM_AUDIO_INTERP{SUFFIX}_COEFFS_H */
''', newline='\n')
    print(f'wrote {out.name}: passband {pb.min():+.3f}..{pb.max():+.3f} dB, stopband <= {sb.max():.1f} dB')


if __name__ == '__main__':
    main()
